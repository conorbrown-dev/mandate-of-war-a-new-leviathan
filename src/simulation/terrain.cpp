Heightfield read_heightfield(const std::string& path) {
    std::ifstream input(path);
    if (!input) throw std::runtime_error("Heightfield file unavailable: " + path);
    std::stringstream buffer;
    buffer << input.rdbuf();
    const auto root = data::JsonParser::parse(buffer.str());
    if (!root) throw std::runtime_error("Heightfield is not valid JSON: " + path);
    const auto format = root->get("format");
    const auto width = root->get("width");
    const auto height = root->get("height");
    const auto heights = root->get("heights");
    if (!format || format->as_string() != "heightfield" || !width || !height || !heights ||
        heights->type() != data::JsonValue::Type::Array) {
        throw std::runtime_error("Malformed heightfield: " + path);
    }
    Heightfield field;
    field.width = static_cast<int>(width->as_number());
    field.height = static_cast<int>(height->as_number());
    const auto& samples = heights->as_array();
    if (field.width <= 0 || field.height <= 0 ||
        samples.size() != static_cast<size_t>(field.width) * static_cast<size_t>(field.height)) {
        throw std::runtime_error("Heightfield size mismatch: " + path);
    }
    field.heights.reserve(samples.size());
    for (const auto& sample : samples) field.heights.push_back(static_cast<float>(sample.as_number()));
    return field;
}

void write_heightfield(const std::string& path, int width, int height, const std::vector<float>& heights) {
    std::ofstream output(path, std::ios::trunc);
    if (!output) throw std::runtime_error("Heightfield file unavailable: " + path);
    output << "{\"format\":\"heightfield\",\"version\":1,\"width\":" << width
           << ",\"height\":" << height << ",\"heights\":[";
    output.precision(9);
    for (size_t index = 0; index < heights.size(); ++index) {
        if (index > 0) output << ',';
        output << heights[index];
    }
    output << "]}\n";
    if (!output) throw std::runtime_error("Heightfield write failed: " + path);
}

void Terrain::load_from_file(const std::string& path) {
    auto field = read_heightfield(path);
    if (field.width != GRID_SIZE || field.height != GRID_SIZE) {
        throw std::runtime_error("Terrain must be a " + std::to_string(GRID_SIZE) + " square grid: " + path);
    }
    heights_ = std::move(field.heights);
}

void Terrain::set_world_bounds(float width, float height) {
    if (width > 0.0f && height > 0.0f && std::isfinite(width) && std::isfinite(height)) {
        world_width_ = width;
        world_height_ = height;
    }
}

bool Terrain::flatten_rect(float x, float y, float half_x, float half_y, float level) {
    if (heights_.empty()) return false;
    const auto grid_x = [this](float world) { return (world / world_width_ + 0.5f) * static_cast<float>(GRID_SIZE - 1); };
    const auto grid_y = [this](float world) { return (world / world_height_ + 0.5f) * static_cast<float>(GRID_SIZE - 1); };
    const int first_x = std::clamp(static_cast<int>(std::floor(grid_x(x - half_x))), 0, GRID_SIZE - 1);
    const int last_x = std::clamp(static_cast<int>(std::ceil(grid_x(x + half_x))), 0, GRID_SIZE - 1);
    const int first_y = std::clamp(static_cast<int>(std::floor(grid_y(y - half_y))), 0, GRID_SIZE - 1);
    const int last_y = std::clamp(static_cast<int>(std::ceil(grid_y(y + half_y))), 0, GRID_SIZE - 1);
    for (int row = first_y; row <= last_y; ++row) {
        for (int column = first_x; column <= last_x; ++column) {
            heights_[row * GRID_SIZE + column] = level;
        }
    }
    ++revision_;
    return true;
}

float Terrain::height_at(float x, float y) const {
    if (x < -world_width_ * 0.5f || x > world_width_ * 0.5f ||
        y < -world_height_ * 0.5f || y > world_height_ * 0.5f) {
        return 0.0f;
    }
    if (heights_.empty()) {
        return 0.0f;
    }

    // Match the vertices generated by Godot: the 320 samples include both
    // world edges. Interpolate the same triangle split used by
    // HeightMap.generate_terrain_mesh() so units do not jump between 125 m
    // sample plateaus while the visible terrain slopes smoothly beneath them.
    const float grid_x = std::clamp(
        (x / world_width_ + 0.5f) * static_cast<float>(GRID_SIZE - 1),
        0.0f, static_cast<float>(GRID_SIZE - 1));
    const float grid_y = std::clamp(
        (y / world_height_ + 0.5f) * static_cast<float>(GRID_SIZE - 1),
        0.0f, static_cast<float>(GRID_SIZE - 1));
    const int x0 = std::min(static_cast<int>(std::floor(grid_x)), GRID_SIZE - 2);
    const int y0 = std::min(static_cast<int>(std::floor(grid_y)), GRID_SIZE - 2);
    const float tx = grid_x - static_cast<float>(x0);
    const float ty = grid_y - static_cast<float>(y0);
    const float h00 = heights_[y0 * GRID_SIZE + x0];
    const float h10 = heights_[y0 * GRID_SIZE + x0 + 1];
    const float h01 = heights_[(y0 + 1) * GRID_SIZE + x0];
    const float h11 = heights_[(y0 + 1) * GRID_SIZE + x0 + 1];
    if (tx + ty <= 1.0f) {
        return h00 + tx * (h10 - h00) + ty * (h01 - h00);
    }
    return h11 + (1.0f - ty) * (h10 - h11) + (1.0f - tx) * (h01 - h11);
}
